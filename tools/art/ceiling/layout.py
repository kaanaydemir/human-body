def fold(name, z, *rows, top, **kw):
    return dict(name=name, z=z, low=[r[:2] for r in rows], under=[r[2] for r in rows], ledge=[r[3] for r in rows],
                lit=[r[4] for r in rows], ink=[r[5] for r in rows], top=top, **kw)


def arc(name, z, *rows, **kw):
    return dict(name=name, z=z, low=[r[:2] for r in rows], T=[r[2] for r in rows], rim=[r[3] for r in rows],
                rc=[r[4] for r in rows], rw=[r[5] for r in rows], hollow=[r[6] for r in rows], **kw)


