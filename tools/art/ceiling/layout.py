# Hand-placed layout for the near ceiling (ceiling_a/b/c.svg, 1920x340, main plane).
#
# Vocabulary (gen_ceiling.py paints them):
#   fold : a long overhanging fold of the lower wall; its lower edge IS the ceiling contour. Rows run left ->
#          right along the lower edge, including the curl of a round end and the cap over its top; `top` closes
#          the shape right -> left (never drawn: it only defines the silhouette and the occlusion of the folds
#          behind). A round end is in front of its neighbour, whose end is tucked behind it. `cap` index ranges
#          are filled with the base so arc feet disappear behind the round end; `caprim` puts a rim on the cap.
#          Row = (x, y, under, ledge, lit, ink): band thicknesses (px) measured up from the edge, ink width.
#   arc  : a vault ring fold overhead, an upward-convex arch. Rows trace its lower (lit) edge from the left foot
#          over the crown to the right foot: (x, y, T face, rim, rc recess core, rw recess, hollow).
#          Feet end inside a cap, inside the tombstone of the arc in front, or taper out on a fold face
#          (`ft` = taper length per foot in index units; `hft` = taper of recess + hollow).
#   back : far arc, only visible in the V gap above two overlapping arcs.
# `rims`, `dash`, `edge`, `streaks`, `cap`, `caprim` are ranges in control-point index units.
#
# Every fold is of one asymmetric kind: its left end is tucked behind the fold before it, a long gentle slope
# runs down to the right into a rounder end (with a cap) that sits in front of the next fold. Lengths, drops
# and slopes vary, so no two neighbouring lobes look alike.
#
# Coordinates: x right, y down. SEAM_* pieces use border-relative x (0 = the tile border) and are painted at
# x=0 and x=1920 in every variant. The seam lobe's round end (x 72-180) hides the first variant fold's tucked
# end and the seam arc's right foot; every variant's last fold has its capped round end at x~1650-1754, where
# the seam arc's left foot stands.

